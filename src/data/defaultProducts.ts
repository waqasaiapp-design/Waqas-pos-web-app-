/**
 * Format currency in Pakistani Rupees (Rs.)
 */
export function formatRs(amount: number): string {
  if (isNaN(amount) || amount === 0) return 'Rs. 0';
  return `Rs. ${amount.toLocaleString('en-PK', { maximumFractionDigits: 0 })}`;
}
